import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const { version } = JSON.parse(readFileSync("package.json", "utf8"));
const check = process.argv.includes("--check");
let drift = false;
for (const root of ["apps", "packages"]) {
  for (const name of readdirSync(root)) {
    const path = join(root, name, "package.json");
    if (!existsSync(path)) continue;
    const manifest = JSON.parse(readFileSync(path, "utf8"));
    manifest.version = version;
    for (const dependencies of [manifest.dependencies, manifest.optionalDependencies]) {
      for (const dependencyName of Object.keys(dependencies ?? {})) {
        if (
          (dependencyName.startsWith("@photoctl/") ||
            dependencyName.startsWith("@dzhng/openphoto-")) &&
          !dependencies[dependencyName].startsWith("workspace:")
        )
          dependencies[dependencyName] = version;
      }
    }
    if (JSON.stringify(JSON.parse(readFileSync(path, "utf8"))) !== JSON.stringify(manifest)) {
      if (check) {
        console.error(`Version drift: ${path}`);
        drift = true;
      } else writeFileSync(path, `${JSON.stringify(manifest, null, 2)}\n`);
    }
  }
}
const swift = "helpers/mac/Sources/photoctl-mac/ReleaseVersion.swift";
const source = `// Generated by scripts/sync-versions.mjs from the root release version.\nlet releaseVersion = ${JSON.stringify(version)}\n`;
if (!existsSync(swift) || readFileSync(swift, "utf8") !== source) {
  if (check) {
    console.error(`Version drift: ${swift}`);
    drift = true;
  } else writeFileSync(swift, source);
}
if (drift) process.exitCode = 1;
